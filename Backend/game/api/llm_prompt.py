#
# ③ 四类判据的**顺序**与 ANNOTATE 相反（修辞→情绪→漏洞→观点），并配了正反例。
#    ANNOTATE 靠配额（观点≥3、漏洞≥1、情绪≥1）逼出分布，一次输出 5-8 张；
#    动态卡是**单张判定，无配额可用**，必须靠判定顺序防止倒向兜底类。
#    这个改动有独立于实测的理论依据（观点是语义兜底类，先判它会吞掉其余三类），
#    真机联调也已经把它证实了。
#
#    实测账目（qwen-turbo, temperature=0.2，累计 29 次调用）：
#    - 耗时全部达标：单次 0.73-1.19s，远低于 15s 后端预算。
#    - **顺序契约已证实生效**：情绪类 3/3 判出「情绪」，而本地关键词池这 3 次
#      全误判观点、全被 AI 纠正——「说明这玩意是能赚钱的啊！」（12字）、
#      「今天，人类正式进入AGI时代！」（15字）、「跟耗材似的」（21字，AI 给的
#      reason 是「比喻+情绪冲击」，说明它看见了比喻，只是在修辞/情绪间权衡，
#      **没跳到第 4 条兜底**）。这正是产品要的：不要求四类按比例出现，
#      只要求观点最后判、该分出来的那类能分出来。
#    - **修辞与漏洞两类至今 0 次被判出，但这不是提示词偏置**。5 个样本逐个读下来
